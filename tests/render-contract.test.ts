import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import { parseContractDocument } from "../src/contract.js";
import { buildSchemaDefinitionFromContract } from "../src/normalize-contract.js";
import { renderPythonModule } from "../src/render-python.js";
import type { SchemaDefinition } from "../src/types.js";

const OPTIONS = {
  moduleName: "models.py",
  headerComment: false,
  schemaHash: "test",
  packageVersion: "2.0.0-test"
};

async function renderFixture(
  name: string,
  options = OPTIONS
): Promise<{ definition: SchemaDefinition; output: string }> {
  const text = await readFile(new URL(`./fixtures/contracts/${name}`, import.meta.url), "utf8");
  const parsed = parseContractDocument(text);
  expect(parsed.diagnostics).toEqual([]);
  const { definition } = buildSchemaDefinitionFromContract(parsed.document!, true);
  return { definition, output: renderPythonModule(definition, options) };
}

function renderDoc(doc: Record<string, unknown>): { definition: SchemaDefinition; output: string } {
  const text = JSON.stringify({
    schemaVersion: "1",
    targetFamily: "sql",
    target: "postgres",
    ...doc
  });
  const parsed = parseContractDocument(text);
  expect(parsed.diagnostics).toEqual([]);
  const { definition } = buildSchemaDefinitionFromContract(parsed.document!, true);
  return { definition, output: renderPythonModule(definition, OPTIONS) };
}

describe("render contract: basic models", () => {
  it("renders checks, native enums, uuid factories, and timestamps", async () => {
    const { output } = await renderFixture("basic-postgres.json");

    expect(output).toContain("CheckConstraint(");
    expect(output).toContain("user_priority_check_dea9d0ab");
    expect(output).toContain("class Role(str, Enum):");
    expect(output).toContain("SAEnum(Role");
    expect(output).toContain("default_factory=uuid4");
    expect(output).toContain("from uuid import UUID, uuid4");
    expect(output).toContain("onupdate=func.now()");
    expect(output).toContain("back_populates='posts'");
    expect(output).toContain("Index('post_userId_idx_a489d58a'");
  });

  it("renders the file header when enabled", async () => {
    const { output } = await renderFixture("basic-postgres.json", {
      moduleName: "models.py",
      headerComment: true,
      schemaHash: "abc123",
      packageVersion: "2.0.0-test"
    });

    expect(output).toContain("# This file is generated by prisma-sqlmodel-gen.");
    expect(output).toContain("# Package version: 2.0.0-test");
    expect(output).toContain("# Schema hash: abc123");
    expect(output).toContain("# Module: models.py");
  });

  it("renders text enums as TEXT columns with Enum annotations", async () => {
    const { output } = await renderFixture("basic-postgres.json");

    expect(output).toContain("class Priority(str, Enum):");
    expect(output).toContain("Column(TEXT()");
    expect(output).toContain("default=Priority.LOW");
    expect(output).not.toContain("SAEnum(Priority");
  });
});

