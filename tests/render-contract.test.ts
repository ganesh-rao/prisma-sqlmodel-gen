describe("render contract: many-to-many and composite keys", () => {
  it("renders link models and composite constraints", async () => {
    const { output } = await renderFixture("join-composite.json");

    expect(output).toContain("link_model=BookTag");
    expect(output).toContain("PrimaryKeyConstraint('orgId', 'teamId')");
    expect(output).toContain("ForeignKeyConstraint(");
  });

  it("omits back_populates for one-sided relations", async () => {
    const { output } = await renderFixture("join-composite.json");

    const tenantLine = output.split("\n").find((line) => line.includes("tenant:"))!;
    expect(tenantLine).toContain("Relationship(sa_relationship_kwargs=");
    expect(tenantLine).not.toContain("back_populates");
    expect(output).not.toContain("back_populates=''");
  });
});

describe("render contract: value objects and variants", () => {
  it("renders value objects ahead of the models that use them", async () => {
    const { output } = await renderFixture("advanced.json");

    expect(output).toContain("class Address(SQLModel):");
    expect(output).toContain("street: str");
    expect(output).toContain("zip: str | None = None");
    expect(output.indexOf("class Address(SQLModel):")).toBeLessThan(output.indexOf("class Doc("));
    expect(output).toContain("address: Address | None = Field(");
  });

  it("renders checks and partial indexes", async () => {
    const { output } = await renderFixture("advanced.json");

    expect(output).toContain("doc_email_len_5aab927d");
    expect(output).toContain("doc_email_active_106036f9");
    expect(output).toContain("postgresql_where=text(");
  });

  it("renders single-table inheritance", async () => {
    const { output } = await renderFixture("advanced.json");

    expect(output).toContain("__mapper_args__ = {'polymorphic_on': 'type'}");
    expect(output).toContain("class Bug(Task):");
    expect(output).toContain("__mapper_args__ = {'polymorphic_identity': 'bug'}");
    const bugStart = output.indexOf("class Bug(Task):");
    const nextClass = output.indexOf("\n\nclass ", bugStart + 1);
    const bugBlock = output.slice(bugStart, nextClass === -1 ? undefined : nextClass);
    expect(bugBlock).not.toContain("__tablename__");
    expect(bugBlock).not.toContain("__table_args__");
    expect(output.indexOf("class Task(SQLModel, table=True):")).toBeLessThan(bugStart);
  });

  it("renders joined-table inheritance", async () => {
    const { output } = await renderFixture("joined-variant.json");

    expect(output).toContain("class Bug(Task, table=True):");
    expect(output).toContain("__tablename__ = 'bug'");
    expect(output).toContain("__mapper_args__ = {'polymorphic_identity': 'bug'}");
  });
});

