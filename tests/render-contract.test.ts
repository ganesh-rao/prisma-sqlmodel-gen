describe("render contract: synthetic edge cases", () => {
  it("renders unique indexes and unnamed checks", () => {
    const { definition, output } = renderDoc({
      storage: {
        namespaces: {
          public: {
            entries: {
              table: {
                t: {
                  columns: {
                    a: { nativeType: "text", codecId: "pg/text@1", nullable: false },
                    b: { nativeType: "text", codecId: "pg/text@1", nullable: true }
                  },
                  indexes: [{ columns: ["b"], name: "u_b", unique: true }],
                  checks: [{ expression: "a <> b" }]
                }
              }
            }
          }
        }
      },
      domain: {
        namespaces: {
          public: {
            models: {
              M: {
                fields: {},
                relations: {},
                storage: { table: "t", namespaceId: "public", fields: {} }
              }
            }
          }
        }
      }
    });

    const unique = definition.models[0]!.constraints.find((entry) => entry.name === "u_b")!;
    expect(unique.unique).toBe(true);
    expect(output).toContain("Index('u_b', 'b', unique=True)");
    expect(output).toContain("CheckConstraint('a <> b')");
    expect(output).not.toContain("CheckConstraint('a <> b', name=");
  });

  it("renders variants with missing bases using the declared name", () => {
    const output = renderPythonModule(
      {
        provider: "postgresql",
        enums: [],
        models: [
          {
            name: "Orphan",
            pythonName: "Orphan",
            tableName: "orphan",
            scalarFields: [],
            relationFields: [],
            constraints: [],
            foreignKeys: [],
            inheritance: { kind: "variant", baseModel: "Missing", value: "x", ownsTable: false }
          }
        ]
      },
      OPTIONS
    );

    expect(output).toContain("class Orphan(Missing):");
  });

  it("renders value object lists and empty value objects", () => {
    const output = renderPythonModule(
      {
        provider: "postgresql",
        enums: [],
        models: [],
        valueObjects: [
          {
            name: "Tags",
            pythonName: "Tags",
            fields: [{ name: "names", pythonName: "names", pythonType: "str", isNullable: false, isList: true }]
          },
          { name: "Empty", pythonName: "Empty", fields: [] }
        ]
      },
      OPTIONS
    );

    expect(output).toContain("names: list[str]");
    expect(output).toContain("class Empty(SQLModel):\n    pass");
  });

  it("orders cyclic value objects without hanging", () => {
    const output = renderPythonModule(
      {
        provider: "postgresql",
        enums: [],
        models: [],
        valueObjects: [
          {
            name: "A",
            pythonName: "A",
            fields: [{ name: "b", pythonName: "b", pythonType: "B", isNullable: true, isList: false }]
          },
          {
            name: "B",
            pythonName: "B",
            fields: [{ name: "a", pythonName: "a", pythonType: "A", isNullable: true, isList: false }]
          }
        ]
      },
      OPTIONS
    );

    expect(output).toContain("class A(SQLModel):");
    expect(output).toContain("class B(SQLModel):");
    expect(output.indexOf("class B(SQLModel):")).toBeLessThan(output.indexOf("class A(SQLModel):"));
  });
});

describe("render contract: real Prisma 8 output", () => {
  it("renders an emitted realworld contract", async () => {
    const { output } = await renderFixture("realworld.json");

    expect(output).toContain("class PostTag(SQLModel, table=True):");
    expect(output).toContain("back_populates='tags'");
    expect(output).toContain("PrimaryKeyConstraint('postId', 'tagId')");
    expect(output).toContain("UniqueConstraint('groupId', 'role')");
    expect(output).toContain("ondelete='CASCADE'");
    expect(output).toContain("onupdate='CASCADE'");
    expect(output).toContain("remote_side");
    expect(output).toContain("TIMESTAMP(precision=3, timezone=True)");
    expect(output).toContain("ARRAY(TEXT())");
    expect(output).toContain("default_factory=uuid4");
    expect(output).toContain("default=0");
    expect(output).toContain("default=Role.MEMBER");
    expect(output).toContain("CheckConstraint");
  });

  it("renders an emitted user-schema contract", async () => {
    const { output } = await renderFixture("user-schema.json");

    expect(output).toContain("class Article(SQLModel, table=True):");
    expect(output).toContain("class FilingChunk(SQLModel, table=True):");
    expect(output).toContain("Index('pgarticle_authors', 'authors', postgresql_using='gin')");
    expect(output).toContain("Index('pgarticle_company_created_at_desc', 'company_id', 'created_at')");
    expect(output).toContain("Index('pgarticle_created_at_desc', 'created_at')");
    expect(output).toContain(
      "UniqueConstraint('filing_id', 'kind', 'ordinal', name='pgfilingchunk_filing_kind_ordinal')"
    );
    expect(output).toContain("UniqueConstraint('ticker', name='pgcompany_ticker')");
    expect(output).toContain("UniqueConstraint('source_url', name='pgfiling_source_url')");
    expect(output).not.toContain("unique=True");
    expect(output).toContain("server_default=text('gen_random_uuid()')");
    expect(output).toContain("TIMESTAMP(precision=6)");
    expect(output).toContain("PG_UUID(as_uuid=True)");
    expect(output).toContain("Column(JSONB(), nullable=False)");
    expect(output).not.toContain("JSON()");
    expect(output).toContain("VARCHAR(255)");
    expect(output).toContain("ondelete='CASCADE'");
    expect(output).toContain("back_populates='articles'");
  });
});
